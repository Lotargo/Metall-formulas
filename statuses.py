def status_badge(key):
    label, _ = STATUSES[key]
    return f'<button type="button" class="status {key}" data-status-help="{key}" popovertarget="status-help-{key}" aria-describedby="status-help-{key}" aria-label="{label}: пояснение статуса"><span>{label}</span><svg class="status-info-icon" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" aria-hidden="true"><circle cx="12" cy="12" r="9"/><path d="M12 11v6M12 7h.01"/></svg></button>'


def status_legend():
    return (
        '<p class="legend-caption no-print">Наведите на статус или нажмите на него, чтобы узнать его смысл.</p><div class="legend" aria-label="Состояния формул">'
        + "".join(status_badge(key) for key in STATUSES)
        + "</div>"
    )


